# (генератор, cap) — cap подобран под реальную комбинаторную ёмкость каждого,
# чтобы ни один шаблон не оказался виден в базе слишком часто
GEN_ENTRIES = [(make_simple_gen(t), cap) for t, cap in SIMPLE_TEMPLATES] + [
    (gen_subject_dream, 55),
    (gen_ipoteka, 30),
    (gen_uvolnenie, 30),
    (gen_kontrakt, 30),
    (gen_metaphor, 70),
    (gen_talkshow, 30),
    (gen_corporate, 25),
    (gen_selfhelp, 25),
    (gen_imageboard, 30),
]

generated = set()
target = sum(cap for _, cap in GEN_ENTRIES)  # предельно достижимый объём при таких лимитах

# исключаем совпадения с уже существующей кураторской базой
curated_path = __import__("pathlib").Path(__file__).parent / "phrases.txt"
curated = set()
try:
    with open(curated_path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                curated.add(line)
except FileNotFoundError:
    pass

counts = [0] * len(GEN_ENTRIES)
attempts = 0
max_attempts = target * 80

while attempts < max_attempts:
    attempts += 1
    # берём только те шаблоны, что ещё не выбрали свой лимит
    available = [i for i, (fn, cap) in enumerate(GEN_ENTRIES) if counts[i] < cap]
    if not available:
        break
    idx = random.choice(available)
    fn, cap = GEN_ENTRIES[idx]
    phrase = fn()
    if "{" in phrase:
        continue
    if phrase in curated or phrase in generated:
        continue
    generated.add(phrase)
    counts[idx] += 1

print(f"Сгенерировано уникальных: {len(generated)} за {attempts} попыток "
      f"(теоретический потолок при текущих лимитах: {target})")

out_path = __import__("pathlib").Path(__file__).parent / "generated_phrases.txt"
with open(out_path, "w", encoding="utf-8") as f:
    for p in sorted(generated):
        f.write(p + "\n")

