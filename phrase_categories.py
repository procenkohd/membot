"""Детерминированная рубрикация фраз для кнопок повторной генерации.

Категории намеренно не хранятся рядом с каждой из 6000+ строк: иначе любое
пополнение базы потребовало бы ручной синхронизации второго файла. Рубрикатор
назначает каждой строке ровно одну категорию и одинаково работает для основной
базы и для одобренных пользовательских фраз.
"""

from __future__ import annotations

import re


GENERAL = "general"
ABSURD = "absurd"
HARD = "hard"
INTELLECTUAL = "intellectual"

CATEGORIES = (GENERAL, ABSURD, HARD, INTELLECTUAL)


# Не только мат, но и грубая лексика: обычная колода не должна внезапно
# подсовывать такое человеку, который не нажимал «Сделай жёстче».
_HARD_RE = re.compile(
    r"(?:"
    r"\bбля(?:дь|ть|ха|[а-я]*)?|"
    r"\b(?:на|по|до|за|а|о|при)?ху(?:й|я|е|ё|и|л|йн|ёв|яр)[а-я]*|"
    r"\bпизд[а-яё]*|\bпезд[а-яё]*|"
    r"\b(?:за|вы|про|под|раз|у|на|от|въ)?[её]б[а-яё]*|"
    r"\bдолбо[её]б[а-яё]*|\bмудак[а-яё]*|\bмраз[а-яё]*|"
    r"\bшлюх[а-яё]*|\bпид[ао]р[а-яё]*|\bгандон[а-яё]*|"
    r"\bсука\b|\bсуч(?:ка|ар)[а-яё]*|"
    r"\bжоп[а-яё]*|\bговн[а-яё]*|\bдерьм[а-яё]*|"
    r"\bсра(?:ть|л|ли|ный|ное|ная|ные)[а-яё]*|\bобосса[а-яё]*"
    r")",
    re.IGNORECASE,
)


_INTELLECTUAL_RE = re.compile(
    r"(?:"
    r"экзистенц|метафиз|онтолог|гносеолог|эпистем|диалектик|"
    r"философ|феноменолог|трансцендент|категорическ.{0,12}императив|"
    r"\bкант\b|ницше|гегел|декарт|платон|аристотел|сократ|"
    r"субъект познания|объект познания|симулякр|парадигм|дискурс|"
    r"герменевт|детерминизм|солипсизм|нигилизм|стоицизм|"
    r"квантов|энтропи|сингулярност|пространств.{0,8}времен|"
    r"теорем|аксиом|гипотез|корреляци|эмпирическ|априори|"
    r"когнитивн|дихотом|имманент|сублимаци|архетип|рефлекси|"
    r"психоанализ|психолог|нейрон|интеллект|рациональн|логическ|"
    r"научн|уч[её]ные|исследован|теоретическ|статистическ|"
    r"аргумент|контраргумент|контекст|концепци|интерпретаци|"
    r"цитат|фактчек|эксперт|аналитик|консенсус|доктрин|"
    r"протокол|регламент|юрисдикци|на основании изложенного|"
    r"логос|деконструк|нарратив|концептуальн|этика добродетели|"
    r"смысл(?:а|ом)? жизни|\bбытие\b|\bбытия\b|\bбытию\b|мироздани"
    r")",
    re.IGNORECASE,
)


# Конкретные носители сюра. Просто слово «кот» само по себе уже создаёт более
# обещанный режиму результат, чем очередная подпись про дедлайн или грусть.
_ABSURD_RE = re.compile(
    r"(?:"
    r"дельфин|гус(?:ь|я|и|ем)|голуб|ворон[а-яё]*|хомяк|капибар|"
    r"енот|жираф|пингвин|улитк|крокодил|осьминог|бобр|ёж|ежа|"
    r"лягуш|кот(?:ик|ёнок|а|ы|ом)?\b|кошк|пёс|пес\b|собак|"
    r"пельмен|майонез|шаурм|кефир|кабач|картош|сосиск|"
    r"бутерброд|гречк|холодильник|табурет|чайник|микроволнов|"
    r"пылесос|носк(?:и|ов)?\b|пакет с пакетами|"
    r"инопланет|марсиан|нло\b|космос|марс\b|лун[аеуы]\b|"
    r"гном|домов(?:ой|ого)|вампир|русалк|колдун|демон|"
    r"симуляци|портал|другая вселенная|параллельн.{0,8}мир|"
    r"превратил(?:ся|ась|ось|ись)|назначил(?:а|и)? совещание|"
    r"захватил(?:а|и)? мир|объявил(?:а|и)? войну|подал[аи]? в суд|"
    r"вступил(?:а|и)? в профсоюз|получил(?:а|и)? гражданство"
    r")",
    re.IGNORECASE,
)


def classify_phrase(phrase: str) -> str:
    """Назначает одну категорию. Приоритет: жёсткая → интеллектуальная → сюр."""
    if _HARD_RE.search(phrase):
        return HARD
    if _INTELLECTUAL_RE.search(phrase):
        return INTELLECTUAL
    if _ABSURD_RE.search(phrase):
        return ABSURD
    return GENERAL
